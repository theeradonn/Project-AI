def normalize_text(text: str) -> str:
    """
    Normalize ข้อความไทยก่อนเทียบ keyword

    - ตัดช่องว่างทั้งหมด (คนไทยพิมพ์เว้นวรรคไม่แน่นอน เช่น "ไม่ รับ ปลายทาง")
    - แปลงเป็นตัวพิมพ์เล็ก (สำหรับคำอังกฤษ เช่น LINE, COD, EMS)

    Args:
        text: ข้อความดิบ

    Returns:
        ข้อความที่ normalize แล้ว พร้อมนำไปเทียบ keyword
    """
    return "".join(text.split()).lower()


# pre-normalize keyword ไว้ล่วงหน้า เพื่อไม่ต้อง normalize ซ้ำทุกครั้งที่เรียก
_NORMALIZED_KEYWORDS: dict[str, list[tuple[str, str]]] = {
    pattern_id: [(normalize_text(kw), kw) for kw in keywords]
    for pattern_id, keywords in FRAUD_KEYWORDS.items()
}


def match_keywords(text: str) -> dict[str, list[str]]:
    """
    หา keyword ที่ match ในข้อความเดียว

    Args:
        text: ข้อความที่ต้องการตรวจ (ปกติคือข้อความของผู้ขาย)

    Returns:
        dict ของ {pattern_id: [keyword ต้นฉบับที่ match]} — dict ว่างถ้าไม่ match อะไรเลย

    Example:
        >>> match_keywords("ไม่รับปลายทางนะคะ โอนก่อนเท่านั้น")
        {'B3': ['ไม่รับปลายทาง', 'โอนก่อนเท่านั้น']}
    """
    if not text or not text.strip():
        return {}

    normalized = normalize_text(text)
    hits: dict[str, list[str]] = {}

    for pattern_id, keyword_pairs in _NORMALIZED_KEYWORDS.items():
        matched = [original for norm_kw, original in keyword_pairs if norm_kw in normalized]
        if matched:
            hits[pattern_id] = matched

    return hits
